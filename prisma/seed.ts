async function main() {
  for (const [name, slug] of categories) {
    await prisma.category.upsert({
      where: { name },
      update: { slug },
      create: { name, slug },
    });
  }

  for (const [name, categorySlug, price, salePrice, unit, imageUrl] of items) {
    const category = await prisma.category.findUniqueOrThrow({ where: { slug: categorySlug } });
    const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-');

    await prisma.product.upsert({
      where: { slug },
      update: {
        name,
        categoryId: category.id,
        price,
        salePrice,
        unit,
        imageUrl,
        description: `Fresh ${name} selected for quality.`,
        stock: 50,
        isActive: true,
      },
      create: {
        name,
        slug,
        categoryId: category.id,
        price,
        salePrice,
        unit,
        imageUrl,
        description: `Fresh ${name} selected for quality.`,
        stock: 50,
      },
    });
  }

  const email = process.env.SEED_ADMIN_EMAIL;
  const password = process.env.SEED_ADMIN_PASSWORD;

  if (!email || !password || password.length < 12) {
    throw new Error('Set SEED_ADMIN_EMAIL and a SEED_ADMIN_PASSWORD of at least 12 characters in .env before seeding.');
  }

  const passwordHash = await bcrypt.hash(password, 12);

  await prisma.user.upsert({
    where: { email },
    update: {},
    create: {
      name: 'FreshMart Admin',
      email,
      passwordHash,
      role: 'ADMIN',
      phone: '+923000000000',
    },
  });

  console.log('Seeded FreshMart categories and 240+ products across all requested departments.');
}

if (process.argv.some((argument) => argument.replace(/\\/g, '/').endsWith('prisma/seed.ts'))) {
  main()
    .catch((error) => {
      console.error('Seed failed:', error);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
